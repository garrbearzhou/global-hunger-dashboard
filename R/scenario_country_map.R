scenario_country_shape_choices <- function() {
  catalog <- scenario_country_shape_catalog()
  stats::setNames(names(catalog), vapply(catalog, function(x) x$label, character(1)))
}

scenario_country_resolve_shape <- function(shape = NULL) {
  catalog <- scenario_country_shape_catalog()
  if (is.null(shape) || !shape %in% names(catalog)) {
    return("continental")
  }
  shape
}

scenario_country_land_path_svg <- function(d, fill_hex, stroke_width = 2) {
  sprintf(
    paste0(
      '<path class="scenario-country-shape" fill="%s" stroke="#0f2a44" ',
      'stroke-width="%.1f" stroke-linejoin="round" stroke-linecap="round" d="%s"/>'
    ),
    fill_hex,
    stroke_width,
    d
  )
}

scenario_country_build_svg <- function(fill_hex, shape = "continental") {
  fill_hex <- gsub("[^#0-9A-Fa-f]", "", fill_hex)
  if (!nzchar(fill_hex)) fill_hex <- "#2d8a54"

  shape_key <- scenario_country_resolve_shape(shape)
  meta <- scenario_country_shape_catalog()[[shape_key]]
  n_paths <- length(meta$paths)

  land_paths <- vapply(
    seq_along(meta$paths),
    function(i) {
      stroke_w <- if (n_paths > 1L && i > 1L) 1.4 else 2
      scenario_country_land_path_svg(meta$paths[[i]], fill_hex, stroke_w)
    },
    character(1)
  )

  paste0(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ', SCENARIO_MAP_VIEW_W, ' ', SCENARIO_MAP_VIEW_H,
    '" role="img" aria-label="Scenario country map">',
    '<defs>',
    '<linearGradient id="sc-ocean-deep" x1="0%" y1="0%" x2="100%" y2="100%">',
    '<stop offset="0%" stop-color="#082f49"/>',
    '<stop offset="45%" stop-color="#0369a1"/>',
    '<stop offset="100%" stop-color="#0c4a6e"/>',
    '</linearGradient>',
    '<filter id="sc-land-shadow" x="-30%" y="-30%" width="160%" height="160%">',
    '<feDropShadow dx="0" dy="4" stdDeviation="5" flood-color="#020617" flood-opacity="0.42"/>',
    '</filter>',
    '</defs>',
    '<rect width="', SCENARIO_MAP_VIEW_W, '" height="', SCENARIO_MAP_VIEW_H, '" fill="url(#sc-ocean-deep)"/>',
    '<g class="scenario-land-group" filter="url(#sc-land-shadow)">',
    paste(land_paths, collapse = ""),
    '</g>',
    '</svg>'
  )
}

scenario_country_landscape_svg <- function(fill_hex, appearance = NULL) {
  shape <- if (is.list(appearance) && !is.null(appearance$shape)) {
    appearance$shape
  } else if (is.character(appearance) && length(appearance) == 1L) {
    appearance
  } else {
    "continental"
  }
  svg <- scenario_country_build_svg(fill_hex, shape)
  src <- paste0(
    "data:image/svg+xml;charset=utf-8,",
    utils::URLencode(svg, reserved = TRUE)
  )
  htmltools::tags$img(
    src = src,
    alt = "Scenario country landscape map",
    class = "scenario-country-map-img"
  )
}
